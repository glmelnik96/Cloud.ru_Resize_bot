"""Перевод исключения в одну фразу, которую можно показать человеку.

До 2026-08-11 в панель прогресса уходил `f"{type(exc).__name__}: {exc}"`. На
проде это означало кусок дампа pydantic со ссылкой на errors.pydantic.dev:
по такому тексту нельзя понять ни что случилось, ни что делать дальше.

Различаем ошибки ПО ИМЕНИ КЛАССА, а не через `isinstance`. Классы моделей
живут в SDK openai, а тянуть его в `app/` запрещено границей импортов
(`tests/contract/test_import_arch.py`, OPENAI_ALLOWED): читать SDK может
только `llm/cloudru.py` и `graph/agent_runner.py`.
"""

from __future__ import annotations

from graph.errors import HumanFacingError

_RETRY = "Запусти генерацию заново."

# Отказ до старта: исключения тут нет, а фраза человеку нужна такая же.
QUEUE_FULL = "Очередь генераций заполнена — попробуй через минуту."

# Имя класса → фраза. Слева и SDK-классы моделей, и наши собственные ошибки:
# для этой таблицы разницы нет, она знает только имена.
_BY_NAME: dict[str, str] = {
    "AgentSchemaError": (
        "Модель не смогла ответить в нужном формате даже со второй попытки. "
        + _RETRY
    ),
    "RateLimitError": (
        "Превышена частота обращений к модели — слишком много запросов подряд. "
        "Подожди минуту и запусти заново."
    ),
    "APIConnectionError": f"Нет связи с сервисом моделей. {_RETRY}",
    "APITimeoutError": (
        f"Связь с сервисом моделей оборвалась по таймауту. {_RETRY}"
    ),
    "InternalServerError": (
        f"Сбой на стороне сервиса моделей. {_RETRY}"
    ),
    "PermissionDeniedError": (
        "Модель недоступна для этого проекта — не выданы права. "
        "Нужна помощь администратора."
    ),
    "NotFoundError": (
        "Модель недоступна: сервис её не знает. Нужна помощь администратора."
    ),
    "HeroGenUnavailable": (
        f"Сервис картинок не ответил, фоновое изображение не получено. {_RETRY}"
    ),
}


def human_error(exc: BaseException) -> str:
    """Одна строка для панели прогресса и для строки в списке задач.

    Без переносов: оба места однострочные.
    """
    if isinstance(exc, HumanFacingError):
        return " ".join(str(exc).split())
    known = _BY_NAME.get(type(exc).__name__)
    if known:
        return known
    # Неизвестную ошибку не прячем совсем: человеку нужно, что показать
    # разработчику, но без стены трейсбека.
    return f"Непредвиденный сбой ({type(exc).__name__}). {_RETRY}"
